<#
  build-installer.ps1 - builds dist\Suite-Setup-<VERSION>.exe.

    1. installer\catalog.ini - the sizes and choices the wizard shows, taken from the apps'
       own catalogs (model catalogs, maps catalog, starter packs), so they never drift apart.
    2. ISCC (Inno Setup 6) compiles installer\Suite-Setup.iss.

  Archive sizes come from Get Archives --list (Kiwix, 2026-10-23); refresh $archiveGB
  when Kiwix's files grow a lot. Sizes are decimal GB, as the wizard shows them.
#>
param([string]$Apps = '', [switch]$CatalogOnly)
$ErrorActionPreference = 'Stop'
$suiteDir = Split-Path $PSScriptRoot -Parent
if (-not $Apps) { $Apps = Split-Path $suiteDir -Parent }
$version = (Get-Content (Join-Path $suiteDir 'VERSION') -Raw).Trim()

# Sizes go into catalog.ini as whole MB (the wizard's Pascal reads integers; no decimal-point trouble).
function MB([string]$s) {
  if ($s -match '([\d.]+)\s*(GB|MB)') { $v = [double]$Matches[1]; if ($Matches[2] -eq 'GB') { $v *= 1000 }; return [int][math]::Round($v) }
  return 0
}
$out = New-Object System.Collections.Generic.List[string]
$out.Add("; Generated by tools\build-installer.ps1 on $(Get-Date -Format 'yyyy-MM-dd') - do not edit by hand.")

# ---- model sizes per graphics-card tier (the apps' data\<N>K-models-catalog.json)
$roles = [ordered]@{ Survival = 'ranger'; General = 'core'; Reasoning = 'logic'; Vision = 'eye' }
$tiers = 4, 8, 12, 24, 32
$out.Add('[tiers]'); $out.Add("list=$($tiers -join ',')")
foreach ($t in $tiers) {
  $c = Get-Content (Join-Path $Apps "AIPortable-JustAI\data\$($t)K-models-catalog.json") -Raw | ConvertFrom-Json
  $out.Add("[tier$t]")
  $i = 0
  foreach ($role in $roles.Keys) {
    $m = $c.models.PSObject.Properties | Where-Object { $_.Value.category -eq $role } | Select-Object -First 1
    if (-not $m) { continue }
    $i++
    $out.Add("m$i=$($roles[$role])|$($m.Value.name)|$($m.Name)|$(MB $m.Value.size)")
  }
  $out.Add("count=$i")
  $emb = $c.models.PSObject.Properties | Where-Object { $_.Value.category -eq 'Embedding' } | Select-Object -First 1
  if ($emb) { $out.Add("embedMB=$(MB $emb.Value.size)") }
}

# ---- map regions (AIPortable data\maps-catalog.json); the author's own 'Local' group is left out
$mc = Get-Content (Join-Path $Apps 'AIPortable\data\maps-catalog.json') -Raw | ConvertFrom-Json
$regions = @($mc.regions.PSObject.Properties | Where-Object { $_.Value.group -ne 'Local' -and $_.Name -ne 'world' })
$out.Add('[maps]'); $out.Add("count=$($regions.Count)")
$out.Add("worldMB=$(MB $mc.regions.world.size)")
$i = 0
foreach ($r in $regions) { $i++; $out.Add("m$i=$($r.Name)|$($r.Value.name)|$(MB $r.Value.size)") }

# ---- starter packs, grouped the way the wizard shows them
$packs = @{}
foreach ($pk in (Get-Content (Join-Path $Apps 'Research\starter\packs.json') -Raw -Encoding UTF8 | ConvertFrom-Json).packs) { $packs[$pk.pack] = $pk }
$archiveGB = @{ appropedia = 0.6; energypedia = 0.8; ifixit = 3.6; medlineplus = 1.9; nhs = 0.015; wikem = 0.3; wikibooks = 3.5
  'se-diy' = 2.1; 'se-gardening' = 0.9; 'se-mechanics' = 0.3; 'se-bicycles' = 0.5; 'se-cooking' = 0.2; 'se-outdoors' = 0.1
  'se-woodworking' = 0.1; 'se-pets' = 0.087; 'se-ham' = 0.077; 'se-homebrew' = 0.037; 'se-sustainability' = 0.028
  'se-crafts' = 0.059; 'se-lifehacks' = 0.049 }
$webGB = @{ wikipedia = 0.3; web = 0.4 }   # fetched page by page, no archive
$groups = [ordered]@{
  med    = @('Medical', 'MedlinePlus, WikEM, NHS Medicines', @('medlineplus', 'wikem', 'nhs'))
  fix    = @('Repair guides', 'iFixit', @('ifixit'))
  diy    = @('Appropriate tech & DIY', 'Appropedia, DIY Stack Exchange', @('appropedia', 'se-diy'))
  energy = @('Off-grid energy', 'energypedia', @('energypedia'))
  se     = @('Everyday Q&A', '12 Stack Exchange sites: gardening, cooking, mechanics, outdoors...', @('se-gardening', 'se-mechanics', 'se-bicycles', 'se-cooking', 'se-outdoors', 'se-woodworking', 'se-pets', 'se-ham', 'se-homebrew', 'se-sustainability', 'se-crafts', 'se-lifehacks'))
  books  = @('Wikibooks', 'Text-only how-to books', @('wikibooks'))
  wiki   = @('Wikipedia articles', 'Hand-picked topics, fetched from wikipedia.org', @('wikipedia'))
  web    = @('Public web pages & PDFs', 'Government and charity guides', @('web'))
}
$out.Add('[packs]'); $out.Add("list=$($groups.Keys -join ',')")
foreach ($g in $groups.Keys) {
  $title, $desc, $keys = $groups[$g]
  $items = 0; $gb = 0.0; $arch = @()
  foreach ($k in $keys) {
    if (-not $packs[$k]) { throw "starter pack '$k' is not in packs.json" }
    $items += $packs[$k].items
    if ($packs[$k].archive) { $arch += $packs[$k].archive; $gb += $archiveGB[$packs[$k].archive] } else { $gb += $webGB[$k] }
  }
  $out.Add("[pack-$g]")
  $out.Add("title=$title"); $out.Add("desc=$desc"); $out.Add("items=$items"); $out.Add("mb=$([int][math]::Round($gb * 1000))")
  $out.Add("packs=$($keys -join ',')"); $out.Add("archives=$($arch -join ',')")
}
$out.Add('[wiki]'); $out.Add('nopicMB=52700'); $out.Add('maxiMB=127400')

# ---- offline archives (AIPortable's data\wikipedia-catalog.json - the same list its Wikipedia tab offers)
# English Wikipedia full text / with pictures are offered separately ([wiki]); the condensed ("mini")
# Wikipedia is never offered - the library tools would build intro-only articles from it.
# An archive a starter pack is built from carries that pack's archive key, so the wizard can show it as included.
$archivesPy = Get-Content (Join-Path $Apps 'Research\_scripts\archives.py') -Raw
$prefixToKey = @{}
foreach ($m in [regex]::Matches($archivesPy, '"([\w-]+)":\s*\("[^"]*",\s*"([^"]+)"')) { $prefixToKey[$m.Groups[2].Value] = $m.Groups[1].Value }
$se = [regex]::Match($archivesPy, 'SE_SITES\s*=\s*\[([^\]]+)\]').Groups[1].Value
foreach ($m in [regex]::Matches($se, '"([\w]+)"')) { $prefixToKey["$($m.Groups[1].Value).stackexchange.com_en_all_"] = "se-$($m.Groups[1].Value)" }
$wc = Get-Content (Join-Path $Apps 'AIPortable\data\wikipedia-catalog.json') -Raw -Encoding UTF8 | ConvertFrom-Json
$cats = @($wc.categories.PSObject.Properties | Sort-Object { $_.Value } | ForEach-Object { $_.Name })
$rows = @()
foreach ($z in $wc.zims.PSObject.Properties) {
  $id = $z.Name; $v = $z.Value
  if ($id -like 'wikipedia_en_all_*') { continue }
  $stem = $id -replace '\.zim$', ''
  $folder = ([uri]$v.url).Segments[-2].TrimEnd('/')
  $name = ($v.name -replace '[^\x20-\x7E]', '-' -replace '\s*\(-\s*[\d.]+ GB\)', '' -replace '--+', '-' -replace '\s+-\s+-?', ' - ').Trim()
  $rows += [pscustomobject]@{ Cat = [array]::IndexOf($cats, $v.category); Category = $v.category; Line = "$id|$name|$(MB $v.size)|$($v.category)|$folder|$($prefixToKey["$($stem)_"])" }
}
$rows = @($rows | Sort-Object Cat)
$out.Add('[archives]'); $out.Add("count=$($rows.Count)")
$i = 0
foreach ($r in $rows) { $i++; $out.Add("a$i=$($r.Line)") }

# ---- the apps themselves (measured on a fresh install; download / on disk)
$out.Add('[base]')
$out.Add('appDlMB=1500'); $out.Add('appDiskMB=2600')       # Node.js, Electron + npm packages, Ollama, Kiwix
$out.Add('voiceDlMB=200'); $out.Add('voiceDiskMB=250')      # whisper.cpp + base.en
$out.Add('researchDlMB=150'); $out.Add('researchDiskMB=500') # Python + the library tools' packages
$out.Add('viewerDlMB=10'); $out.Add('viewerDiskMB=300')
$out.Add('pagesPercent=25')                                 # built library pages, as a share of the archive size

$catalog = Join-Path $suiteDir 'installer\catalog.ini'
[IO.File]::WriteAllLines($catalog, $out)
Write-Host "Wrote $catalog"
if ($CatalogOnly) { return }

$iscc = @("$env:LOCALAPPDATA\Programs\Inno Setup 6\ISCC.exe", "${env:ProgramFiles(x86)}\Inno Setup 6\ISCC.exe") | Where-Object { Test-Path $_ } | Select-Object -First 1
if (-not $iscc) { throw 'Inno Setup 6 is not installed (winget install JRSoftware.InnoSetup)' }
& $iscc "/DSuiteVersion=$version" "/O$(Join-Path $suiteDir 'dist')" (Join-Path $suiteDir 'installer\Suite-Setup.iss')
if ($LASTEXITCODE -ne 0) { throw 'ISCC failed' }
